function textMapper(life,context){
 const names=protectedNames(life),nameSet=new Set(names),namePattern=names.length?new RegExp('('+names.map(regexEscape).join('|')+')','gu'):null,map=replacements(context),pattern=new RegExp(Object.keys(map).sort((a,b)=>b.length-a.length).map(regexEscape).join('|'),'gu');
 return text=>{if(typeof text!=='string')return text;return (namePattern?text.split(namePattern):[text]).map(part=>nameSet.has(part)?part:part.replace(pattern,match=>map[match])).join('');};
}
export function localizeText(life,text){const context=localeForLife(life);return context?textMapper(life,context)(text):text;}
function phaseFor(age){return age<12?'child':age<24?'youth':age<40?'adult':age<56?'middle':age<74?'late':'elder';}
function fill(text,c){return text.replace(/\{(country|place|market|school|workshop|station)\}/g,(_,key)=>key==='country'?c.country.name:key==='place'?c.cohortPlace:c[key]);}

