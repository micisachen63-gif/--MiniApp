export function realLifeIdentity(life){
 if(!valid(life))return null;
 const gender=(hash('real-life-gender-v1:'+life.seed)&1)?'f':'m';
 return {gender,genderLabel:gender==='f'?'女性':'男性',birth:birthGeography(life.seed)};
}
function careerFrom(life,id){
 const base=CAREER_BY_ID.get(id),identity=realLifeIdentity(life),first=lifeTiming(life).choiceAges[0];
 const qualificationAge=base.trainingYears?Math.max(base.minAge,first+base.trainingYears):null;
 return {...base,...(base.id==='home-care'?{name:identity.gender==='f'?'家庭主婦／家庭照顧者':'家庭主夫／家庭照顧者'}:{}),place:identity.birth.name+'的'+base.place,
  minAge:Math.max(base.minAge,qualificationAge||0),qualificationAge,requiredEducationIndex:base.requiredEducationIndex||0};
}
export function realCareer(life){
 if(!valid(life))return null;
 const pair=pairFor(life),answer=life.answers?.[0]===1?1:0;
 return careerFrom(life,pair[answer]);
}

