const replace=(text,values)=>text.replace(/\{(\w+)\}/g,(_,key)=>values[key]||'');
export function realScenes(life){
 if(!valid(life))return [];
 const timing=lifeTiming(life),pair=pairFor(life),candidates=pair.map(id=>careerFrom(life,id)),identity=realLifeIdentity(life),selected=realCareer(life);
 const values={country:identity.birth.name,a:candidates[0].name,b:candidates[1].name,career:selected.name,place:selected.place};
 return [0,1,2].map(stage=>{
  const family=(byte(life.seed,stage)>>>4)%8,template=[FIRST,SECOND,THIRD][stage][family],age=timing.choiceAges[stage];
  const base={id:`v6-real-scene-${stage}-${family}`,scenarioId:`v6-real-${stage}-${family}`,age,tag:`第${['一','二','三'][stage]}章 · ${template[0]}`,title:replace(template[1],values),text:replace(template[2],values)};
  if(stage!==0)return {...base,choices:[template[3].map(text=>replace(text,values)),template[4].map(text=>replace(text,values))]};
  return {...base,careerIds:[...pair],choices:candidates.map(career=>{
   const prep=career.requiredEducationIndex?'先補修進修，完成所在地所需培訓與資格確認。':career.adultOnly?'僅規劃二十一歲後所在地允許的成人工作，先談清費用、安全與界線。':career.id==='home-care'?'談好家務、長輩照顧與開銷分工，保留自己的生活和日後轉換空間。':'先了解技能、工作要求與實際日常，接受學習和適應需要時間。';
   const cost=career.requiredEducationIndex?'培訓與等待會占去時間和預備金，現在的選擇還不是立即上工。':career.adultOnly?'夜間與人際應對會影響作息，任何超出約定的要求都可以拒絕。':career.id==='home-care'?'有酬收入可能減少，照顧責任也不能只靠一個人默默承擔。':'收入、工作時間與照顧責任需要重新安排，並不保證選了就順利。';
   const label=(career.adultOnly&&age<21?'規劃21歲後投入':'選擇準備')+' '+career.name;
   return [label,prep+cost,`你選擇準備${career.name}這條路。${prep}${cost}`];
  })};
 });
}
