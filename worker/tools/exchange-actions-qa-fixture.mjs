const ACCOUNT = '90101', PEERS = ['90201', '90202'];
const REALMS = [['permanent', 'DB'], ['season_2026_01', 'DB_SEASON']];
const digest = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const setupId = (realm, n) => (realm === 'permanent' ? 'ea110000' : 'ea220000') + '-0000-4000-8000-' + String(n).padStart(12, '0');
const rows = (db, sql, ...args) => db.sqlite.prepare(sql).all(...args);

function requireIsolated(env, now) {
  if (env.ENVIRONMENT !== 'development' || env.ALLOW_DEV_AUTH !== 'true'
      || !env.DB?.sqlite || !env.DB_SEASON?.sqlite || env.DB.sqlite === env.DB_SEASON.sqlite
      || !Number.isSafeInteger(now) || now <= 0) throw Error('Exchange actions QA requires two isolated development SQLite fixtures');
}

function databaseSnapshot(db) {
  const schema = rows(db, 'SELECT type,name,tbl_name,sql FROM sqlite_master ORDER BY type,name');
  const names = rows(db, "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name").map(row => row.name);
  const tables = names.map(name => [name, rows(db, 'SELECT * FROM "' + name.replaceAll('"', '""') + '" ORDER BY rowid')]);
  return { sha256: digest({ schema, tables }), tableCount: names.length, tableNames: names,
    totalChanges: db.sqlite.prepare('SELECT total_changes() AS n').get().n,
    listingCount: db.sqlite.prepare('SELECT COUNT(*) AS n FROM rpg_exchange_listings').get().n,
    operationCount: db.sqlite.prepare('SELECT COUNT(*) AS n FROM rpg_exchange_operations').get().n,
    ledgerCount: db.sqlite.prepare('SELECT COUNT(*) AS n FROM rpg_ledger').get().n };
}

async function stock(db, id, item, quantity) {
  await db.prepare('INSERT INTO rpg_inventory(tg_id,item,quantity) VALUES(?,?,?) ON CONFLICT(tg_id,item) DO UPDATE SET quantity=excluded.quantity')
    .bind(id, item, quantity).run();
}

async function gear(db, id, key, now, overrides = {}) {
  const value = { ...makeGear({ id:key, tgId:id, cls:'sword', slot:'helmet', tier:2,
    rng:()=>0.2, now, source:'local-exchange-actions-qa', forceRarity:'advanced' }), ...overrides };
  await insertEquipStmt(db, value).run();
  return value;
}

function sigil(db, charId, id, now, overrides = {}) {
  const value = { id, char_id:charId, type:'magic', quality:2, bound:0, active:0, locked:0,
    trade_id:null, exchange_id:null, ...overrides };
  // Guardian provenance is an explicit synthetic initial input, separate from
  // the exchange setup receipts that are generated by the original authority.
  const sourceOperationId=id+':synthetic-input', accountId=db.sqlite.prepare('SELECT account_tg_id FROM rpg_characters WHERE tg_id=?').get(charId).account_tg_id;
  db.sqlite.prepare("INSERT INTO rpg_guardian_operations(operation_id,account_id,char_id,request_id,action,payload_hash,config_version,cost_json,result_json,created_at) VALUES(?,?,?,?,'summon',?,?,?, ?,?)")
    .run(sourceOperationId,accountId,charId,sourceOperationId,digest({syntheticInputOnly:true,sigilId:id}),'exchange-actions-qa-inputs-v1','{}',JSON.stringify({syntheticInputOnly:true,sigilId:id}),now);
  db.sqlite.prepare('INSERT INTO rpg_guardian_sigils(id,char_id,type,quality,bound,active,locked,trade_id,source_operation_id,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?)')
    .run(value.id,value.char_id,value.type,value.quality,value.bound,value.active,value.locked,value.trade_id,sourceOperationId,now,now);
  return value;
}

async function seedRealm(env, realmId, binding, now) {
  const db=env[binding], sql=db.sqlite, scoped=scopeEnvForRealm(env,await resolveRealm(env,realmId));
  const characters=rows(db,'SELECT tg_id,account_tg_id,name,base_class FROM rpg_live_characters WHERE account_tg_id=? ORDER BY char_slot',ACCOUNT);
  const main=characters.find(row=>row.base_class==='sword')||characters[0], alternate=characters.find(row=>row.base_class==='archer')||null;
  const manifest={realmId,mainAccountId:ACCOUNT,mainCharacterId:main.tg_id,alternateCharacterId:alternate?.tg_id||null,
    peers:[],assets:{},protected:{},setupOperations:[],listingTargets:{}};
  for (const [index,accountId] of PEERS.entries()) {
    const player=await Player.createCharacter(scoped,{tgId:accountId,charSlot:1,name:'合成交易旅人'+(index+1),baseClass:'sword',gender:'f'},now);
    manifest.peers.push({accountId,characterId:player.char.tg_id});
  }
  for (const actor of [...characters,...manifest.peers.map(peer=>({tg_id:peer.characterId}))])
    sql.prepare("UPDATE rpg_characters SET gold=2000000,level=60,party_id=NULL,last_settle_at=? WHERE tg_id=?").run(now,actor.tg_id);

  const prefix='exchange-actions-qa:'+realmId+':';
  manifest.assets.availableEquipment=[];
  for(let i=0;i<35;i++){
    const value=await gear(db,main.tg_id,prefix+'sale-gear-'+String(i).padStart(2,'0'),now,
      {enhance_level:i===0?7:i%4,...(i===34?{name:'暮星長路・'+'原詞條與強化完整保留'.repeat(8)}:{})});
    manifest.assets.availableEquipment.push(value.id);
  }
  manifest.assets.createEquipment=manifest.assets.availableEquipment[0];
  manifest.assets.fullStack={item:'scroll_w',quantity:17};
  await stock(db,main.tg_id,'scroll_w',17);
  await stock(db,main.tg_id,'scroll_a',23);
  await stock(db,main.tg_id,'hunt_1_1',3);
  await stock(db,main.tg_id,'research_fragment',7);
  manifest.assets.createGuardian=sigil(db,main.tg_id,prefix+'sale-guardian',now).id;
  manifest.protected.boundEquipment=(await gear(db,main.tg_id,prefix+'bound-gear',now,{bound:1,enhance_level:9})).id;
  manifest.protected.equipped=rows(db,'SELECT id FROM rpg_equipment WHERE tg_id=? AND is_equipped=1 ORDER BY id',main.tg_id).map(row=>row.id);
  manifest.protected.lockedGuardian=sigil(db,main.tg_id,prefix+'locked-guardian',now,{locked:1}).id;
  manifest.protected.boundGuardian=sigil(db,main.tg_id,prefix+'bound-guardian',now,{bound:1}).id;
  manifest.protected.boundItem='research_fragment';

  let sequence=0;
  async function setupListing(actor,kind,input,label) {
    await selectAccountCharacter(scoped,actor.accountId,actor.characterId,now);
    const requestId=setupId(realmId,++sequence),body={requestId,characterId:actor.characterId,...input};
    const response=await Exchange.create(scoped,actor.characterId,body,now);
    const receipt=sql.prepare('SELECT account_tg_id,request_id,char_id,action,payload_json,result_json,created_at FROM rpg_exchange_operations WHERE account_tg_id=? AND request_id=?')
      .get(actor.accountId,requestId);
    if(!receipt||receipt.action!=='create'||JSON.parse(receipt.result_json).listingId!==response.result.listingId)
      throw Error('Original exchange setup receipt missing');
    const result={label,kind,accountId:actor.accountId,characterId:actor.characterId,requestId,body,
      listingId:response.result.listingId,result:response.result,payload:JSON.parse(receipt.payload_json),createdAt:receipt.created_at};
    manifest.setupOperations.push(result);
    manifest.listingTargets[label]={listingId:result.listingId,kind,ref:input.equipId||input.item||input.guardianId,
      sellerAccountId:actor.accountId,sellerCharacterId:actor.characterId,qty:input.qty,price:input.price,fee:Math.ceil(input.price/20)};
  }
  const peer=manifest.peers[0];
  manifest.assets.buyEquipment=(await gear(db,peer.characterId,prefix+'buy-gear',now,{enhance_level:7})).id;
  await setupListing(peer,'equip',{equipId:manifest.assets.buyEquipment,qty:1,price:101},'buyEquipment');
  await stock(db,peer.characterId,'scroll_a',9);
  await setupListing(peer,'item',{item:'scroll_a',qty:9,price:203},'buyStack');
  manifest.assets.buyGuardian=sigil(db,peer.characterId,prefix+'buy-guardian',now,{quality:3,type:'melee'}).id;
  await setupListing(peer,'guardian',{guardianId:manifest.assets.buyGuardian,qty:1,price:307},'buyGuardian');

  const primary={accountId:ACCOUNT,characterId:main.tg_id};
  await setupListing(primary,'item',{item:'scroll_a',qty:5,price:409},'cancelStack');
  if(alternate){
    const altGear=await gear(db,alternate.tg_id,prefix+'alternate-cancel-gear',now,{enhance_level:6});
    manifest.assets.alternateCancelEquipment=altGear.id;
    await setupListing({accountId:ACCOUNT,characterId:alternate.tg_id},'equip',{equipId:altGear.id,qty:1,price:503},'cancelAlternateEquipment');
  }
  await selectAccountCharacter(scoped,ACCOUNT,main.tg_id,now);
  manifest.setupRequestIds=manifest.setupOperations.map(row=>row.requestId);
  manifest.assetsHash=digest(manifest.assets);
  return manifest;
}

export async function seedExchangeActionsQa(env, now) {
  requireIsolated(env,now);
  for(const [,binding] of REALMS){
    const db=env[binding];
    if(db.sqlite.prepare('SELECT COUNT(*) AS n FROM rpg_exchange_listings').get().n
      ||db.sqlite.prepare('SELECT COUNT(*) AS n FROM rpg_exchange_operations').get().n)
      throw Error('Exchange actions QA requires an empty exchange; reseeding is forbidden');
    if(!db.sqlite.prepare('SELECT 1 FROM rpg_live_characters WHERE account_tg_id=?').get(ACCOUNT))
      throw Error('Exchange actions QA requires initial main characters in both realms');
    if(PEERS.some(accountId=>db.sqlite.prepare('SELECT 1 FROM rpg_accounts WHERE account_tg_id=?').get(accountId)))
      throw Error('Exchange actions QA peer accounts already exist; reseeding is forbidden');
  }
  const realms={};
  for(const [realmId,binding] of REALMS)realms[realmId]=await seedRealm(env,realmId,binding,now);
  return {schemaVersion:1,fixtureVersion:1,synthetic:true,initialInputsOnly:false,authoritySetupExplicit:true,
    setupNotAcceptance:true,noDispatcher:true,realNotificationsSent:false,seededAt:now,accountId:ACCOUNT,
    realms,manifestSha256:digest(realms)};
}

function realmState(db, manifest) {
  const sql=db.sqlite;
  return {
    characters:rows(db,'SELECT tg_id AS characterId,account_tg_id AS accountId,name,base_class AS baseClass,gold,rev,party_id AS partyId FROM rpg_live_characters ORDER BY account_tg_id,char_slot'),
    selections:rows(db,'SELECT account_tg_id AS accountId,active_char_id AS characterId FROM rpg_accounts ORDER BY account_tg_id'),
    operations:rows(db,'SELECT account_tg_id AS accountId,request_id AS requestId,char_id AS characterId,action,payload_json,result_json,created_at AS createdAt FROM rpg_exchange_operations ORDER BY account_tg_id,request_id')
      .map(({payload_json,result_json,...row})=>({...row,payload:JSON.parse(payload_json),result:JSON.parse(result_json)})),
    listings:rows(db,'SELECT * FROM rpg_exchange_listings ORDER BY seq'),
    equipment:rows(db,"SELECT * FROM rpg_equipment WHERE id LIKE 'exchange-actions-qa:%' ORDER BY id"),
    guardians:rows(db,"SELECT * FROM rpg_guardian_sigils WHERE id LIKE 'exchange-actions-qa:%' ORDER BY id"),
    inventory:rows(db,"SELECT tg_id AS characterId,item,quantity FROM rpg_inventory WHERE item IN ('scroll_w','scroll_a','hunt_1_1','research_fragment') ORDER BY tg_id,item"),
    exchangeLedger:rows(db,"SELECT id,event_id,tg_id,type,gold_delta,item,item_delta,exp_delta,created_at FROM rpg_ledger WHERE event_id LIKE 'exchange:%' ORDER BY id"),
    setupOperationCount:manifest.setupRequestIds.length,
    acceptanceOperationCount:sql.prepare('SELECT COUNT(*) AS n FROM rpg_exchange_operations').get().n-manifest.setupRequestIds.length
  };
}

export function exchangeActionsQaState(env, seed) {
  requireIsolated(env,seed?.seededAt);
  if(seed?.synthetic!==true||seed?.setupNotAcceptance!==true||seed?.manifestSha256!==digest(seed.realms))
    throw Error('Exchange actions QA initial manifest changed');
  return {ok:true,schemaVersion:1,synthetic:true,isolated:true,ephemeral:true,productionAccess:false,
    noDispatcher:true,realNotificationsSent:false,seed,
    databases:{permanent:databaseSnapshot(env.DB),season:databaseSnapshot(env.DB_SEASON)},
    permanent:realmState(env.DB,seed.realms.permanent),
    season:realmState(env.DB_SEASON,seed.realms.season_2026_01)};
}
