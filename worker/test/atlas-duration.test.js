test('legacy count request signature replays after upgrade without starting or reserving again', async t => {
  const { env, db, id } = await serviceFixture(t);
  const legacy = { requestId: 'legacy-request-001', mapId: 'laurel_intro', mapCount: 1, durationMinutes: 60, supplies: { hp: 10, mp: 10 } };
  await Atlas.start(env, id, legacy, T0);
  const record = saved(db, id), state = JSON.parse(record.state_json);
  state.ruleset_version = 'atlas-v1';
  delete state.queueMode;
  delete state.balanceProfile.goldMultiplier;
  delete state.balanceProfile.experienceMultiplier;
  db.prepare('UPDATE rpg_atlas_runs SET state_json=? WHERE id=?').run(JSON.stringify(state), record.id);
  const storedSignature = db.prepare('SELECT signature FROM rpg_atlas_operations WHERE request_id=?').get(legacy.requestId).signature;
  assert.equal(storedSignature, JSON.stringify({ charId: id, mapId: legacy.mapId, mapCount: 1, durationMinutes: 60, supplies: legacy.supplies }));
  const before = inventory(db, id);
  const replay = await Atlas.start(env, id, legacy, T0 + 1000);
  assert.equal(replay.run.queueMode, 'count');
  assert.deepEqual(inventory(db, id), before);
  const done = await Atlas.settle(env, id, {}, T0 + 3600000);
  assert.equal(done.run.status, 'completed');
  assert.equal(done.run.completedMaps, 1);
  assert.equal(done.run.report.reason, 'queue_completed');
});

test('duration service catches up a full high-power window in bounded commits and reconciles its ledger', async t => {
  const { env, db, id } = await serviceFixture(t);
  // Synthetic equipment, not a representative production balance measurement.
  db.prepare('UPDATE rpg_equipment SET base_stat=100000 WHERE tg_id=?').run(id);
  const equipment = db.prepare('SELECT * FROM rpg_equipment ORDER BY id').all();
  await Atlas.start(env, id, startBody({ durationMinutes: 480, supplies: { hp: 0, mp: 0 } }), T0);
  let result, chunks = 0, processed = 0;
  do {
    result = await Atlas.settle(env, id, {}, T0 + 50 * 86400000);
    const state = JSON.parse(saved(db, id).state_json);
    assert.ok(state.elapsedSeconds - processed <= 2000);
    processed = state.elapsedSeconds;
    assert.ok(++chunks <= 15);
  } while (result.run.status === 'running');
  assert.equal(processed, 28800);
  assert.equal(result.run.status, 'completed');
  assert.ok(result.run.completedMaps > 96);
  const earned = db.prepare("SELECT SUM(gold_delta) gold,SUM(exp_delta) exp,COUNT(*) n FROM rpg_ledger WHERE type='星圖掉落'").get();
  assert.equal(earned.gold, result.run.report.gold);
  assert.equal(earned.exp, result.run.report.exp);
  const state = JSON.parse(saved(db, id).state_json);
  assert.equal(earned.n, state.rewardSequence);
  assert.deepEqual(db.prepare('SELECT * FROM rpg_equipment ORDER BY id').all(), equipment);
  assert.equal(db.prepare('SELECT completions FROM rpg_atlas_progress WHERE char_id=?').get(id).completions, result.run.completedMaps);
  await Atlas.settle(env, id, {}, T0 + 60 * 86400000);
  assert.equal(db.prepare("SELECT COUNT(*) n FROM rpg_ledger WHERE type='星圖掉落'").get().n, earned.n);
});

