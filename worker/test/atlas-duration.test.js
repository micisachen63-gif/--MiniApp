const START = 1800000000;
const strong = { characterId: 'synthetic-high-investment', baseClass: 'sword', level: 100,
  atk: 100000, def: 100000, maxHp: 10000, maxMp: 1000 };
const input = extra => ({ runId: 'duration-fixture', realmId: 'permanent', seed: 'duration-seed',
  startAt: START, durationSeconds: 28800, queueMode: 'duration', mapId: 'laurel_intro',
  buildId: 'sword_whirlwind', snapshot: strong, supplies: { hp: 20, mp: 20 }, ...extra });
function finish(run, now = START + 28800, maxSteps = 2000) {
  const rewards = [];
  let result;
  do {
    result = advanceAtlasRun(run, now, { maxSteps });
    run = result.state;
    rewards.push(...result.rewards);
  } while (result.stillCatchingUp);
  return { state: run, rewards };
}

test('duration dispatch passes 96 clears and uses exactly the accepted eight-hour window', () => {
  const run = createAtlasRun(input());
  const result = finish(run, START + 50 * 86400);
  assert.equal(result.state.status, 'completed');
  assert.equal(result.state.stopReason, 'duration_reached');
  assert.equal(result.state.elapsedSeconds, 28800);
  assert.equal(result.state.mapCount, null);
  assert.ok(result.state.metrics.mapsCompleted > 96);
  assert.equal(result.state.metrics.combatSeconds + result.state.metrics.travelSeconds, 28800);
  assert.equal(result.rewards.filter(r => r.kind === 'completion').length, result.state.metrics.mapsCompleted);
  assert.equal(new Set(result.rewards.map(r => r.id)).size, result.rewards.length);
  assert.deepEqual(advanceAtlasRun(result.state, START + 100 * 86400).rewards, []);
});

test('online chunks, offline catch-up and JSON reload have identical duration rewards and supplies', () => {
  const original = createAtlasRun(input({ durationSeconds: 3700 }));
  const all = finish(original);
  let state = original;
  const rewards = [];
  for (const elapsed of [0, 5, 89, 89, 201, 1800, 3501, 4000]) {
    const part = finish(JSON.parse(JSON.stringify(state)), START + elapsed, 113);
    state = part.state;
    rewards.push(...part.rewards);
  }
  assert.deepEqual(state, all.state);
  assert.deepEqual(rewards, all.rewards);
  assert.equal(state.supplies.hp + state.supplies.hpUsed, 20);
  assert.equal(state.supplies.mp + state.supplies.mpUsed, 20);
});

